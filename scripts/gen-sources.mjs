// Embeds the files that runway uploads to AWS (agent, image sources, CloudFormation
// template) into src/generated/sources.ts, so the bundled CLI and the maintainer Lambda carry
// them without reading files at runtime. Runs before typecheck, tests and builds.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const files = {
  agent: 'agent/runway_agent.py',
  installRunner: 'images/install-runner.sh',
  microvmDockerfile: 'images/microvm/Dockerfile',
  waitForDocker: 'images/microvm/wait-for-docker.sh',
  fargateDockerfile: 'images/container/Dockerfile.fargate',
  lambdaDockerfile: 'images/container/Dockerfile.lambda',
  buildspec: 'images/container/buildspec.yml',
  template: 'template/runway.yaml',
};

// GitHub's webhook ranges, baked in as the template's default.
// The CLI passes fresh ones and the maintainer refreshes the API weekly, so a slightly old list is fine.
let hookCidrs;
try {
  const res = await fetch('https://api.github.com/meta', {
    headers: { 'user-agent': 'mintwork-runway-build' },
  });
  hookCidrs = (await res.json()).hooks;
  if (!Array.isArray(hookCidrs) || hookCidrs.length === 0) throw new Error('no hooks');
  writeFileSync('template/github-hook-cidrs.txt', `${hookCidrs.join('\n')}\n`);
} catch {
  hookCidrs = readFileSync('template/github-hook-cidrs.txt', 'utf8').split('\n').filter(Boolean);
}

/** runway.yaml with the shared function environment expanded in place (CloudFormation has no YAML anchors). */
export function expandTemplate() {
  const env = readFileSync('template/environment.yaml', 'utf8')
    .split('\n')
    .filter((l) => l.trim() && !l.startsWith('#'))
    .map((l) => `          ${l}`)
    .join('\n');
  const out = readFileSync('template/runway.yaml', 'utf8').replace(
    /^ {6}Environment: ['"]@@RUNWAY_ENVIRONMENT@@['"]$/gm,
    `      Environment:\n        Variables:\n${env}`,
  );
  const withCidrs = out.replace('"@@GITHUB_HOOK_CIDRS@@"', JSON.stringify(hookCidrs.join(',')));
  if (withCidrs.includes('@@'))
    throw new Error('template/runway.yaml: a placeholder was not expanded');
  return withCidrs;
}

const read = (path) =>
  path === 'template/runway.yaml' ? expandTemplate() : readFileSync(path, 'utf8');
const body = Object.entries(files)
  .map(([name, path]) => `/** ${path} */\nexport const ${name} = ${JSON.stringify(read(path))};`)
  .join('\n\n');
mkdirSync('src/generated', { recursive: true });
writeFileSync(
  'src/generated/sources.ts',
  `// Generated by scripts/gen-sources.mjs. Do not edit.\n\n${body}\n`,
);
mkdirSync('dist', { recursive: true });
writeFileSync('dist/runway.template.yaml', expandTemplate());
